import { Alert, Checkbox, Form, Input, Modal } from 'antd';
import { useState } from 'react';
import type { GmailAppPassword } from '../../api/gmailTemporary';
import { useI18n } from '../../i18n';
import { defineMessage } from '../../i18n/messages';

const copy = {
  title: defineMessage('emails.gmailPassword.title', '使用 Google 应用专用密码', 'Use a Google app password'),
  email: defineMessage('emails.gmailPassword.email', 'Gmail 邮箱地址', 'Gmail address'),
  invalidEmail: defineMessage('emails.gmailPassword.invalidEmail', '请输入有效邮箱地址。', 'Enter a valid email address.'),
  password: defineMessage('emails.gmailPassword.password', '应用专用密码', 'App password'),
  invalidPassword: defineMessage('emails.gmailPassword.invalidPassword', '请输入 Google 生成的 16 位应用专用密码。', 'Enter the 16-character app password generated by Google.'),
  save: defineMessage('emails.gmailPassword.save', '加密保存，供下次使用', 'Encrypt and save for next time'),
  note: defineMessage('emails.gmailPassword.note', '请使用 Google 生成的应用专用密码。不勾选保存时，关闭 Gmail 工作区或刷新页面后需要重新输入。', 'Use an app password generated by Google. Without saving, you will need to enter it again after leaving the Gmail workspace or reloading.'),
  connect: defineMessage('emails.gmailPassword.connect', '连接', 'Connect'),
  cancel: defineMessage('emails.gmailPassword.cancel', '取消', 'Cancel'),
  failed: defineMessage('emails.gmailPassword.failed', '连接失败。请检查应用专用密码或账号是否允许 IMAP 访问；如果账号已保存，请先在邮箱列表管理原连接。', 'Connection failed. Check the app password and whether the account allows IMAP. If this address is already saved, manage its existing connection in the mailbox list.'),
} as const;

interface Fields extends GmailAppPassword {
  save?: boolean;
}

export default function GmailPasswordDialog({
  onClose,
  onConnect,
}: {
  onClose: () => void;
  onConnect: (credentials: GmailAppPassword, save: boolean) => Promise<boolean>;
}) {
  const { t } = useI18n();
  const [form] = Form.useForm<Fields>();
  const [connecting, setConnecting] = useState(false);
  const [failed, setFailed] = useState(false);

  const submit = async ({ email, password, save }: Fields) => {
    if (connecting) return;
    setConnecting(true);
    setFailed(false);
    try {
      if (await onConnect({ email: email.trim().toLowerCase(), password: password.trim().replaceAll(' ', '') }, save === true)) {
        form.resetFields();
        onClose();
      } else {
        setFailed(true);
      }
    } finally {
      setConnecting(false);
    }
  };

  return (
    <Modal
      open
      title={t(copy.title)}
      okText={t(copy.connect)}
      cancelText={t(copy.cancel)}
      confirmLoading={connecting}
      cancelButtonProps={{ disabled: connecting }}
      closable={!connecting}
      mask={{ closable: !connecting }}
      keyboard={!connecting}
      onCancel={onClose}
      onOk={() => form.submit()}
      destroyOnHidden
    >
      <Form form={form} layout="vertical" autoComplete="off" preserve={false} disabled={connecting} onFinish={submit}>
        <Form.Item name="email" label={t(copy.email)} rules={[{ type: 'email', required: true, message: t(copy.invalidEmail) }]}>
          <Input type="email" autoComplete="off" />
        </Form.Item>
        <Form.Item name="password" label={t(copy.password)} rules={[{
          required: true, pattern: /^ *(?:[a-zA-Z0-9] *){16}$/, message: t(copy.invalidPassword),
        }]}>
          <Input.Password autoComplete="off" maxLength={32} />
        </Form.Item>
        <Form.Item name="save" valuePropName="checked">
          <Checkbox>{t(copy.save)}</Checkbox>
        </Form.Item>
        <Alert type={failed ? 'error' : 'info'} title={t(failed ? copy.failed : copy.note)} showIcon />
      </Form>
    </Modal>
  );
}
